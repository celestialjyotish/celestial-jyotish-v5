def get_source(source_id: str) -> SourceDefinition | None:
    """Return a source definition by its registry identifier."""

    normalized_id = source_id.strip().upper()

    for source in SOURCE_REGISTRY:
        if source.source_id == normalized_id:
            return source

    return None


def get_sources_by_type(
    source_type: SourceType,
) -> tuple[SourceDefinition, ...]:
    """Return all registered sources belonging to a source type."""

    return tuple(
        source
        for source in SOURCE_REGISTRY
        if source.source_type == source_type
    )


def get_research_hierarchy() -> tuple[SourceDefinition, ...]:
    """Return registered sources in research-priority order."""

    return tuple(
        sorted(
            SOURCE_REGISTRY,
            key=lambda source: source.priority,
        )
    )


def is_model_inference(source_type: SourceType) -> bool:
    """Return True when a source type represents model-generated inference."""

    return source_type == SourceType.MODEL_INFERENCE