from dataclasses import dataclass
from enum import IntEnum

from schemas.astrology import SourceType


class SourcePriority(IntEnum):
    """Priority used when evaluating evidence for astrology claims."""

    PRIMARY_CLASSICAL = 1
    AUTHORITATIVE_BOOK = 2
    SCHOLAR = 3
    JOURNAL = 4
    REPUTABLE_MODERN = 5
    MODEL_INFERENCE = 6


@dataclass(frozen=True)
class SourceDefinition:
    """Definition of a research source or source family."""

    source_id: str
    title: str
    source_type: SourceType
    priority: SourcePriority
    description: str
    verification_required: bool = True


